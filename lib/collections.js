// Sets que salen para un idioma y una era (cualquiera de los dos puede faltar → se juntan).
export function setsDe(idioma, era) {
  const idiomas = idioma ? [idioma] : Object.keys(SETS);
  const eras = era ? [era] : Object.keys(ERAS_ORDEN);
  const out = [];
  idiomas.forEach((i) => eras.forEach((e) => out.push(...(SETS[i]?.[e] || []))));
  return [...new Set(out)];
}
const ERAS_ORDEN = { vintage: 1, media: 2, moderno: 3 };

// Lo que se ofrece al elegir colección al subir una carta: Lote siempre primero.
// Pokémon necesita idioma y era; mientras falte alguno solo se ofrece Lote.
export function coleccionesPara(game, idioma, era) {
  if (game !== 'Pokémon' || !idioma || !era) return [LOTE];
  return [LOTE, ...setsDe(idioma, era)];
}

// Para las cartas antiguas (que solo tenían la colección japonesa): deduce idioma y era.
export function inferirIdiomaEra(collection) {
  if (!collection || collection === LOTE) return { idioma: '', era: '' };
  for (const era of Object.keys(ERAS_ORDEN)) {
    if (SETS.ja[era].includes(collection)) return { idioma: 'ja', era };
  }
  return { idioma: '', era: '' };
}

